// Deal specs. Dates are given as "days ago" and turned into real dates by build.ts,
// so the demo always looks current. Owner = the client's owner.
//
// Open deals: `days` = days in the current stage.
// Won/Lost:   `days` = days since the deal was closed; `closedFrom` = last open stage.

import type {
  ApplicationStatus,
  Bank,
  LossReason,
  OpenStageKey,
  Product,
  StageKey,
} from '../../constants';

export interface AppSpec {
  bank: Bank;
  status: ApplicationStatus;
  /** Approved/disbursed amount if it differs from the request. */
  amount?: number;
  rate?: number;
  termMonths?: number;
  rejectionReason?: string;
  submittedDaysAgo?: number;
  decidedDaysAgo?: number;
}

export interface DealSpec {
  id: string;
  clientId: string;
  product: Product;
  amount: number;
  purpose: string;
  stage: StageKey;
  days: number;
  closedFrom?: OpenStageKey;
  lostReason?: LossReason;
  apps?: AppSpec[];
}

const A = (
  bank: Bank,
  status: ApplicationStatus,
  extra: Omit<AppSpec, 'bank' | 'status'> = {},
): AppSpec => ({
  bank,
  status,
  ...extra,
});

